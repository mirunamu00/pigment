import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { strToU8, zipSync } from "fflate";
import { flattenTokens } from "@pigment/schema";
import { rel } from "../paths.ts";
import { loadTemplate, resolveTokens, type LoadedTemplate } from "../template.ts";
import { listFiles, ok, writeJson, writeText } from "../util.ts";

function cssName(path: string): string {
  return `--${path.replaceAll(".", "-").replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase()}`;
}

function cssValue(value: unknown, type?: string): string {
  if (type === "cubicBezier" && Array.isArray(value)) return `cubic-bezier(${value.join(", ")})`;
  if (typeof value === "string" || typeof value === "number") return String(value);
  if (Array.isArray(value)) return value.map((v) => (typeof v === "string" && v.includes(" ") ? `"${v}"` : String(v))).join(", ");
  return JSON.stringify(value);
}

/** tokens.css: primitives + light semantics on :root, dark semantics on [data-theme=dark] and prefers-color-scheme. */
export function buildCss(tpl: LoadedTemplate): string {
  const lines: string[] = [`/* ${tpl.manifest.name} ${tpl.version} — generated by pnpm harness bundle. Do not edit. */`];
  const block = (selector: string, entries: Map<string, { value: unknown; type?: string }>, filter: (p: string) => boolean) => {
    lines.push(`${selector} {`);
    for (const [path, token] of entries) if (filter(path)) lines.push(`  ${cssName(path)}: ${cssValue(token.value, token.type)};`);
    lines.push("}");
  };
  const semanticPaths = (tree?: LoadedTemplate["primitives"]) => new Set(tree ? flattenTokens(tree).map((t) => t.path) : []);
  const light = tpl.modes.light ?? tpl.modes.dark;
  const lightResolved = resolveTokens(tpl.primitives, light);
  block(":root", lightResolved, () => true);
  if (tpl.modes.dark && tpl.modes.light) {
    const darkResolved = resolveTokens(tpl.primitives, tpl.modes.dark);
    const darkOnly = semanticPaths(tpl.modes.dark);
    block('[data-theme="dark"]', darkResolved, (p) => darkOnly.has(p));
    lines.push("@media (prefers-color-scheme: dark) {");
    lines.push('  :root:not([data-theme="light"]) {');
    for (const [path, token] of darkResolved) if (darkOnly.has(path)) lines.push(`    ${cssName(path)}: ${cssValue(token.value, token.type)};`);
    lines.push("  }", "}");
  }
  return lines.join("\n") + "\n";
}

function tokenTable(resolved: Map<string, { value: unknown; type?: string }>, prefix: string): string {
  const rows = [...resolved].filter(([p]) => p.startsWith(prefix));
  if (rows.length === 0) return "";
  return ["| Token | Value |", "| --- | --- |", ...rows.map(([p, t]) => `| \`${p}\` | \`${cssValue(t.value, t.type)}\` |`)].join("\n");
}

/** agent.md: the single document an agent reads. Most important content first. */
export function buildAgentMd(tpl: LoadedTemplate): string {
  const { manifest } = tpl;
  const principles = tpl.read(manifest.artifacts.principles);
  const instructions = tpl.read(manifest.artifacts.instructions);
  const components = tpl.components.components
    .filter((c) => c.status !== "unsupported" && c.file)
    .map((c) => tpl.read(join("components", c.file!)).trim());
  const unsupported = tpl.components.components.filter((c) => c.status === "unsupported").map((c) => c.name);

  const sections: string[] = [
    `# ${manifest.name} ${manifest.version}`,
    `Design system \`${manifest.id}@${manifest.version}\`. ${manifest.description}`,
    "This document is the complete design specification. Use the values and rules here instead of your own defaults. " +
      "Where something is not specified, choose the option most consistent with the rules below and say so in your report. " +
      "Token values are also provided as `tokens.css` and `tokens.json` next to this file — copy them, do not retype them. " +
      "Each token's CSS variable is its path with dots replaced by dashes and camelCase split by dashes: " +
      "`color.text.onAction` → `--color-text-on-action`.",
    principles.trim(),
  ];
  for (const [mode, tree] of Object.entries(tpl.modes)) {
    const resolved = resolveTokens(tpl.primitives, tree);
    sections.push(`## Semantic color tokens — ${mode}`, tokenTable(resolved, "color."));
  }
  const primitives = resolveTokens(tpl.primitives);
  // Every primitive group except raw colors (agents must use semantic colors), in the template's own order.
  const groups = Object.keys(tpl.primitives).filter((g) => !g.startsWith("$") && g !== "color" && g !== "palette");
  sections.push(
    "## Primitive tokens",
    ...groups.map((g) => tokenTable(primitives, `${g}.`)).filter(Boolean),
    "## Components",
    ...components,
  );
  if (unsupported.length) sections.push(`Not specified in this version: ${unsupported.join(", ")}. Build them from the rules above and list them in your report.`);
  sections.push(instructions.trim());
  return sections.join("\n\n") + "\n";
}

export function bundle(id: string, version: string): string {
  return bundleTemplate(loadTemplate(id, version));
}

export function bundleTemplate(tpl: LoadedTemplate): string {
  const { id, version } = tpl;
  const dist = join(tpl.dir, "dist");
  const css = buildCss(tpl);
  const resolvedByMode = Object.fromEntries(
    Object.entries(tpl.modes).map(([mode, tree]) => [mode, Object.fromEntries([...resolveTokens(tpl.primitives, tree)].map(([p, t]) => [p, t.value]))]),
  );
  writeText(join(dist, "tokens.css"), css);
  writeJson(join(dist, "tokens.json"), { id, version, modes: resolvedByMode });
  writeText(join(dist, "agent.md"), buildAgentMd(tpl));

  // Offline package: the source files + the built ones, under a folder named <id>-<version>.
  const files: Record<string, Uint8Array> = {};
  for (const file of listFiles(tpl.dir, (f) => !f.endsWith(".zip"))) {
    const name = `${id}-${version}/${file.slice(tpl.dir.length + 1).replaceAll("\\", "/")}`;
    files[name] = new Uint8Array(readFileSync(file));
  }
  files[`${id}-${version}/README.txt`] = strToU8(
    `${tpl.manifest.name} ${version}\nStart with dist/agent.md. Give your coding agent this folder's path.\n`,
  );
  // A fixed mtime keeps the archive byte-identical for identical input, so its hash is stable.
  const zipped = zipSync(files, { level: 9, mtime: new Date("2000-01-01T00:00:00Z") });
  writeFileSync(join(dist, `${id}-${version}.zip`), zipped);
  ok(`bundled ${rel(dist)} (agent.md, tokens.css, tokens.json, ${id}-${version}.zip)`);
  return dist;
}
